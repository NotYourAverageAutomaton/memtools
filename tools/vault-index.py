#!/usr/bin/env python3
"""vault-index — regenerate the generated half of index.md below a marker; the hand-written top is never touched.

The generated half: page counts per folder, the resident rules (if [layout] rules_dir is set), pages claiming
`status: active` in the arcs folder, and how to search. It refuses to write past a size limit, because an
agent's harness may auto-load only the start of the file. Such a harness cuts the file off past a limit,
without saying so, and the limit has changed over time: set [index] max_lines and max_bytes to what yours reports.
Dry run unless --apply.
"""
from __future__ import annotations

import argparse
import re
import sys
from collections import defaultdict
from datetime import date, datetime
from pathlib import Path

from memtools_config import layout, load_config, vault_root

VAULT = vault_root()
CONFIG = load_config(VAULT)
LAY = layout(CONFIG)
ICFG = CONFIG.get("index", {}) or {}
INDEX = VAULT / "index.md"
LOG = VAULT / "log.md"
MARKER = "<!-- AUTO-MAP: regenerated by vault-index.py; everything ABOVE is hand-written -->"

APPLIED = re.compile(r"^##\s*\[(\d{4}-\d{2}-\d{2})\]\s*applied\s*\|\s*\[\[([^\]|#]+)(?:[|#][^\]]*)?\]\]", re.M)   # v1.4.1: [[page|alias]] and [[page#heading]] count as page
TRUNCATE_CLIFF = int(ICFG["max_bytes"]) if "max_bytes" in ICFG else None
LINE_CAP = int(ICFG["max_lines"]) if "max_lines" in ICFG else None
WARN_AT = int(TRUNCATE_CLIFF * 0.85) if TRUNCATE_CLIFF else None
WARN_LINES = int(LINE_CAP * 0.85) if LINE_CAP else None


def frontmatter(text: str) -> dict:
    if not text.startswith("---"):
        return {}
    end = text.find("\n---", 3)
    if end == -1:
        return {}
    fm = {}
    for line in text[3:end].splitlines():
        m = re.match(r"^([a-z_]+):\s*(.*)$", line.strip())
        if m:
            fm[m.group(1)] = m.group(2).strip()
    return fm


def one_liner(p: Path) -> str:
    """The page's own first bolded claim or first prose line — its reason to exist."""
    txt = p.read_text(encoding="utf-8", errors="ignore")
    body = txt[txt.find("\n---", 3) + 4:] if txt.startswith("---") else txt
    for line in body.splitlines():
        s = line.strip()
        if not s or s.startswith(("#", "---", "|", ">", "```")):
            continue
        s = re.sub(r"\*\*|\*|`", "", s).strip(" -·")
        if len(s) > 25:
            return s[:150] + ("…" if len(s) > 150 else "")
    return ""


def applied_days() -> dict[str, int]:
    seen = defaultdict(set)
    for src in sorted(VAULT.glob("log.md")) + sorted(VAULT.glob("log_*.md")):
        for day, page in APPLIED.findall(src.read_text(encoding="utf-8", errors="ignore")):
            seen[page].add(day)
    return {k: len(v) for k, v in seen.items()}


def build_map() -> str:
    days = applied_days()
    counts = defaultdict(int)
    for p in VAULT.rglob("*.md"):
        if any(d in p.parts for d in LAY["exclude_dirs"]) or p.name in ("index.md", "log.md"):
            continue
        rel = p.relative_to(VAULT).parts
        counts[rel[0] if len(rel) > 1 else "."] += 1
    total = sum(counts.values())

    out = [MARKER, "", "## Map", "",
           f"*Regenerated {date.today()} by vault-index.py from the folder itself. **{total} pages.***", ""]
    for k in sorted(counts):
        out.append(f"- `{k}/` — **{counts[k]}**" if k != "." else f"- top level — **{counts[k]}**")
    out += ["", "Search instead of browsing:", "",
            "```",
            'vault-recall.py "what you want to know"',
            "vault-recall.py --arcs",
            "vault-recall.py --open <page-stem>",
            "```", ""]

    if LAY["rules_dir"] and (VAULT / LAY["rules_dir"]).is_dir():
        rules = sorted((VAULT / LAY["rules_dir"]).glob("*.md"))
        out += ["## Rules (resident on purpose)", "",
                f"*All {len(rules)} promoted rules, ordered by distinct days applied (from the log).*", ""]
        rows = sorted((-days.get(p.stem, 0), p.stem, one_liner(p)) for p in rules)
        for negd, stem, line in rows:
            mark = f"**{-negd}x** " if negd else ""
            out.append(f"- {mark}[[{stem}]] — {line}" if line else f"- {mark}[[{stem}]]")
        out.append("")

    arcs_dir = VAULT / LAY["arcs_dir"]
    if arcs_dir.is_dir():
        arcs = []
        for p in sorted(arcs_dir.glob("*.md")):
            fm = frontmatter(p.read_text(encoding="utf-8", errors="ignore"))
            if fm.get("status") != "active":
                continue
            rev = fm.get("last_reviewed", "")
            try:
                age = (date.today() - datetime.strptime(rev, "%Y-%m-%d").date()).days
            except ValueError:
                age = 9999
            arcs.append((age, p.stem, rev))
        out += ["## Active work", "", "*Read the page before touching the work: the page outranks memory.*", ""]
        for age, stem, rev in sorted(arcs):
            flag = "" if age <= 7 else ("  ← stale, still claims active" if age > 30 else "  ← cooling")
            out.append(f"- `{age:>3}d` [[{stem}]] ({rev or '?'}){flag}")
        out += ["", f"*{len(arcs)} claim active; {sum(1 for a, _, _ in arcs if a <= 7)} touched in 7 days.*", ""]
    return "\n".join(out)


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--apply", action="store_true")
    ap.add_argument("--vault", help="the notes folder (default: MEMTOOLS_VAULT or the current folder)")
    a = ap.parse_args()

    text = INDEX.read_text(encoding="utf-8") if INDEX.exists() else "# Index\n"
    head = text.split(MARKER)[0].rstrip() if MARKER in text else text.rstrip()
    new = head + "\n\n" + build_map() + "\n"

    nlines = new.count("\n") + 1
    print(f"index.md: {len(text):,} -> {len(new):,} bytes, {nlines} lines")
    if TRUNCATE_CLIFF is None and LINE_CAP is None:
        print("  note: no [index] max_lines / max_bytes set. If a harness auto-loads this file, set them to what it reports.")
    if WARN_AT and len(new) > WARN_AT:
        print(f"  WARNING: {len(new):,} bytes is past 85% of max_bytes ({TRUNCATE_CLIFF:,}). Move retired blocks out of the top.")
    if TRUNCATE_CLIFF and len(new) > TRUNCATE_CLIFF:
        print(f"  ERROR: {len(new):,} bytes is past max_bytes ({TRUNCATE_CLIFF:,}). Refusing to write.", file=sys.stderr)
        return 1
    if WARN_LINES and nlines > WARN_LINES:
        print(f"  WARNING: {nlines} lines is past 85% of max_lines ({LINE_CAP}).")
    if LINE_CAP and nlines > LINE_CAP:
        print(f"  ERROR: {nlines} lines is past max_lines ({LINE_CAP}). The bottom would not load, silently. Refusing to write.\n"
              f"  Trim the hand-written top: it is the only part this tool cannot shrink.", file=sys.stderr)
        return 1

    if not a.apply:
        print("\n--- dry run; re-run with --apply ---")
        print(build_map()[:1500])
        return 0

    INDEX.write_text(new, encoding="utf-8")
    print("  written.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
