#!/usr/bin/env python3
"""vault-discover — propose the links your notes are missing, not only report the broken ones.

Triadic closure: A links B and B links C, but A does not link C. Also lists orphans (nothing links to
them) and dead ends (they link to nothing). --write keeps the result in discoveries.md (or --out).
"""
from __future__ import annotations

import argparse
import re
import sys
from collections import Counter, defaultdict
from datetime import datetime
from pathlib import Path

from memtools_config import layout, load_config, vault_root

VAULT = vault_root()
OUT = VAULT / "discoveries.md"
MARKER = "<!-- AUTO-DISCOVERY: regenerated by vault-discover.py; edit ABOVE this line -->"

WIKILINK = re.compile(r"\[\[([^\]|#]+)")
EXCLUDE = {"index", "log", "MEMORY", "AGENTS", "README", "discoveries"}
EXCLUDE_PREFIXES = ("hot-tier-archive-", "log_")
EXCLUDE_DIRS = layout(load_config(VAULT))["exclude_dirs"]


def load_pages() -> dict[str, Path]:
    pages = {}
    for p in sorted(VAULT.rglob("*.md")):
        if any(d in p.parts for d in EXCLUDE_DIRS):
            continue
        if (p.stem in EXCLUDE or p.stem.startswith("health-report-")
                or p.stem.startswith(EXCLUDE_PREFIXES)):
            continue
        pages[p.stem] = p
    return pages


def build_graph(pages: dict[str, Path]) -> tuple[dict[str, set], Counter]:
    out: dict[str, set] = {}
    inbound: Counter = Counter()
    for stem, path in pages.items():
        try:
            text = path.read_text(errors="ignore")
        except OSError:
            text = ""
        links = {m.strip() for m in WIKILINK.findall(text)}
        links = {l for l in links if l in pages and l != stem}
        out[stem] = links
        for l in links:
            inbound[l] += 1
    return out, inbound


def triadic(out: dict[str, set], top: int) -> list[tuple[str, str, list[str]]]:
    """A→B, B→C, but no A→C. Ranked by how many distinct B's bridge A and C —"""
    bridges: dict[tuple[str, str], set] = defaultdict(set)
    for a, bs in out.items():
        for b in bs:
            for c in out.get(b, ()):
                if c == a or c in out[a]:
                    continue
                if a in out.get(c, set()):
                    continue
                key = (a, c) if a < c else (c, a)
                bridges[key].add(b)
    ranked = sorted(bridges.items(), key=lambda kv: (-len(kv[1]), kv[0]))
    return [(a, c, sorted(bs)) for (a, c), bs in ranked[:top]]


def semantic(pages: dict[str, Path], out: dict[str, set], top: int):
    """Optional: high-similarity pages not yet linked. Degrades to None without deps."""
    try:
        from sentence_transformers import SentenceTransformer
        import numpy as np
    except ImportError:
        return None
    stems = list(pages)
    texts = []
    for s in stems:
        try:
            texts.append(pages[s].read_text(errors="ignore")[:2000])
        except OSError:
            texts.append("")
    model = SentenceTransformer("BAAI/bge-small-en-v1.5")
    emb = model.encode(texts, normalize_embeddings=True, show_progress_bar=False)
    sim = np.asarray(emb) @ np.asarray(emb).T
    hits = []
    for i, a in enumerate(stems):
        for j in range(i + 1, len(stems)):
            b = stems[j]
            if b in out[a] or a in out[b]:
                continue
            hits.append((float(sim[i][j]), a, b))
    hits.sort(reverse=True)
    return hits[:top]


def render(pages, out, inbound, tri, orphans, deadends, sem, top) -> str:
    L = []
    A = L.append
    A(f"*generated {datetime.now():%Y-%m-%d %H:%M} · {len(pages)} pages · "
      f"{sum(len(v) for v in out.values())} resolvable links · "
      f"{sum(len(v) for v in out.values())/max(len(out),1):.1f} per page*")
    A("")
    A(f"## 🔺 Triadic closure — connections waiting to be drawn *(top {len(tri)})*")
    A("*A links B, B links C, but A and C have never been connected. The more distinct")
    A("bridges, the stronger the case. Draw the link, or note why it doesn't belong.*")
    A("")
    if tri:
        for a, c, bs in tri:
            via = ", ".join(f"[[{b}]]" for b in bs[:3]) + ("…" if len(bs) > 3 else "")
            A(f"{len(bs)}× **[[{a}]]** ⟷ **[[{c}]]** — via {via}")
    else:
        A("*(none)*")
    A("")
    A(f"## 🕳️ Orphans — nothing links to these *({len(orphans)})*")
    A("*An orphan is no longer INVISIBLE — since 2026-07-31 `vault-recall.py` full-text-searches")
    A("every page, so an unlinked page is still findable by asking for it. What an orphan loses is")
    A("the second hop: recall expands one step along wikilinks, so an orphan can never be surfaced")
    A("as a NEIGHBOUR of something you were already reading — it is reachable only if you already")
    A("guessed its vocabulary. Link it from where it belongs, or prune it.*")
    A("")
    for s in orphans:
        A(f"- [[{s}]]")
    A("")
    A(f"## 🚪 Dead ends — these link to nothing *({len(deadends)})*")
    A("*A page with no outbound links can be found but leads nowhere — it never")
    A("contributes to a throughline.*")
    A("")
    for s in deadends:
        A(f"- [[{s}]]")
    A("")
    A("## 🧲 Semantic overlap — similar but unlinked")
    if sem is None:
        A("")
        A("*Inactive: `sentence-transformers` not installed. Triadic carries the signal")
        A("on a graph this dense; install it only if you want the second opinion.*")
    elif sem:
        A("")
        for score, a, b in sem:
            A(f"- {score:.3f} **[[{a}]]** ⟷ **[[{b}]]**")
    return "\n".join(L)


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--write", action="store_true", help="write the result to --out (default: discoveries.md in the notes folder)")
    ap.add_argument("--out", help="where --write puts the result")
    ap.add_argument("--vault", help="the notes folder (default: MEMTOOLS_VAULT or the current folder)")
    ap.add_argument("--top", type=int, default=20)
    args = ap.parse_args()
    global OUT
    if args.out:
        OUT = Path(args.out).expanduser().resolve()

    pages = load_pages()
    if not pages:
        print("no pages found", file=sys.stderr)
        return 1
    out, inbound = build_graph(pages)
    tri = triadic(out, args.top)
    orphans = sorted(s for s in pages if inbound.get(s, 0) == 0)
    deadends = sorted(s for s, links in out.items() if not links)
    sem = semantic(pages, out, args.top) if args.write else None

    body = render(pages, out, inbound, tri, orphans, deadends, sem, args.top)
    print(body)

    if args.write:
        head = (f"# Discoveries: connections the notes have not drawn yet\n\n"
                f"*Generated {datetime.now():%Y-%m-%d} by vault-discover.py. Write above the marker; below it is regenerated.*\n")
        if OUT.exists():
            prev = OUT.read_text(errors="ignore")
            if MARKER in prev:
                head = prev.split(MARKER)[0]
        OUT.parent.mkdir(parents=True, exist_ok=True)
        OUT.write_text(f"{head}\n{MARKER}\n\n{body}\n")
        print(f"\n→ wrote {OUT}", file=sys.stderr)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
